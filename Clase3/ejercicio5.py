"""
5. Suma de tres números
Consigna: Pide al usuario tres números y muestra la suma total.
"""

print ("Sumaremos los tres numeros que ingreses")

# Solicitamos los numeros al usuario
num1= int(input("Ingrese el primer numero: "))

num2= int(input("Ingrese el segundo numero: "))

num3= int(input("Ingrese el tercer numero: "))

# Sumamos los numeros
print ("La suma de los numeros ingresados es de:", num1 + num2 + num3)